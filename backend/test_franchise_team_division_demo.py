import os
import django
import uuid

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "core.settings")
django.setup()

from django.contrib.auth import get_user_model
from rest_framework.test import APIClient
from rest_framework import status
from users.models import Products, Franchise, Organization
from franchise.models import (
    ClientLicenseRequest,
    ClientInvoice,
    OrganizationProduct,
    OrganizationUser,
)

User = get_user_model()

def run_franchise_team_demo():
    print("\n" + "=" * 80)
    print("DEMO: FRANCHISE TEAM ROLE DIVISION WORKFLOW & CLIENT TCS ONBOARDING")
    print("=" * 80)

    client = APIClient()

    # Verify our demo users exist
    priya = User.objects.get(username="priya.tiwari")
    ashutosh = User.objects.get(username="ashutosh.dhyande")
    harshit = User.objects.get(username="harshit.nigam")
    aakash = User.objects.get(username="aakash.dehriya")

    hrmsm = Products.objects.filter(code="hrms").first()
    sfa = Products.objects.filter(code="sfa").first()
    assert hrmsm is not None and sfa is not None, "Products HRMSM and SFA must exist"

    # =========================================================================
    # STEP 1: FRANCHISE_SALES (priya.tiwari) raises subscription request for TCS
    # =========================================================================
    print("\n[STEP 1] FRANCHISE_SALES (priya.tiwari) logs in and raises subscription request...")
    res_login_sales = client.post("/api/franchise/login/", {
        "username": "priya.tiwari",
        "password": "franchise"
    }, format="json")
    assert res_login_sales.status_code == status.HTTP_200_OK, f"Priya login failed: {res_login_sales.data}"
    token_sales = res_login_sales.data["access"]
    client.credentials(HTTP_AUTHORIZATION=f"Bearer {token_sales}")

    payload_request = {
        "client_name": "Tata Consultancy Services",
        "client_email": "contact@tcs.com",
        "client_phone": "9876543210",
        "organization_name": "tcs",
        "billing_address": "TCS House, Raveline Street, Fort, Mumbai",
        "city": "Mumbai",
        "state": "Maharashtra",
        "pincode": "400001",
        "customer_gstin": "27AAACT2727Q1ZB",
        "notes": "Annual enterprise license package: 15 HRMSM seats + 10 SFA seats",
        "items": [
            {
                "product": hrmsm.id,
                "license_count": 15,
                "duration_months": 12,
            },
            {
                "product": sfa.id,
                "license_count": 10,
                "duration_months": 12,
            }
        ]
    }

    res_req = client.post("/api/franchise/license-requests/", payload_request, format="json")
    assert res_req.status_code == status.HTTP_201_CREATED, f"Failed creating license request: {res_req.data}"
    license_request_id = res_req.data["id"]
    quoted_amount = res_req.data["quoted_amount"]
    print(f"--> PASSED: Request #{license_request_id} created by FRANCHISE_SALES (priya.tiwari)")
    print(f"    Organization: 'tcs'")
    print(f"    Products: HRMSM (15 seats) + SFA (10 seats)")
    print(f"    Total Quoted Amount: INR {quoted_amount}")
    print(f"    Status: {res_req.data['status']}")

    # =========================================================================
    # STEP 2: FRANCHISE_ACCOUNTANT (ashutosh.dhyande) reviews, generates invoice & sends email
    # =========================================================================
    print("\n[STEP 2] FRANCHISE_ACCOUNTANT (ashutosh.dhyande) logs in, generates invoice & sends email...")
    res_login_acc = client.post("/api/franchise/login/", {
        "username": "ashutosh.dhyande",
        "password": "franchise"
    }, format="json")
    assert res_login_acc.status_code == status.HTTP_200_OK, f"Ashutosh login failed: {res_login_acc.data}"
    token_acc = res_login_acc.data["access"]
    client.credentials(HTTP_AUTHORIZATION=f"Bearer {token_acc}")

    # Generate Invoice from Request
    res_inv = client.post(f"/api/franchise/license-requests/{license_request_id}/generate-invoice/", {}, format="json")
    assert res_inv.status_code == status.HTTP_201_CREATED, f"Generate invoice failed: {res_inv.data}"
    invoice_id = res_inv.data["invoice"]["id"]
    invoice_num = res_inv.data["invoice"]["invoice_number"]
    total_inv_amount = res_inv.data["invoice"]["total_amount"]
    print(f"--> PASSED: ClientInvoice #{invoice_num} generated by FRANCHISE_ACCOUNTANT (ashutosh.dhyande)")
    print(f"    Invoice Total: INR {total_inv_amount}")
    print(f"    Request status updated to: {res_inv.data['request_status']}")

    # Send Email to Client for payment of subscription plans
    res_email = client.post(f"/api/franchise/invoices/{invoice_id}/send-email/", {
        "email": "billing@tcs.com"
    }, format="json")
    assert res_email.status_code == status.HTTP_200_OK, f"Send email failed: {res_email.data}"
    print(f"--> PASSED: Invoice email sent to billing@tcs.com with payment breakdown.")

    # Record client payment (Mark invoice paid)
    res_paid = client.post(f"/api/franchise/invoices/{invoice_id}/mark-paid/", {
        "payment_method": "bank_transfer",
        "payment_reference": "TCS_NEFT_998822"
    }, format="json")
    assert res_paid.status_code == status.HTTP_200_OK, f"Mark paid failed: {res_paid.data}"
    req_obj = ClientLicenseRequest.objects.get(id=license_request_id)
    assert req_obj.status == ClientLicenseRequest.Status.PAID
    print(f"--> PASSED: Payment confirmed. Request #{license_request_id} status is now: 'paid' (Ready for IT)")

    # =========================================================================
    # STEP 3: FRANCHISE_IT (harshit.nigam) fulfills & provisions TCS & rata.tata
    # =========================================================================
    print("\n[STEP 3] FRANCHISE_IT (harshit.nigam) logs in, provisions 'tcs' & creates 'rata.tata'...")
    res_login_it = client.post("/api/franchise/login/", {
        "username": "harshit.nigam",
        "password": "franchise"
    }, format="json")
    assert res_login_it.status_code == status.HTTP_200_OK, f"Harshit login failed: {res_login_it.data}"
    token_it = res_login_it.data["access"]
    client.credentials(HTTP_AUTHORIZATION=f"Bearer {token_it}")

    # Check if rata.tata already exists from earlier, if so remove or update
    User.objects.filter(username="rata.tata").delete()

    res_fulfill = client.post(f"/api/franchise/license-requests/{license_request_id}/fulfill/", {
        "org_admin_username": "rata.tata",
        "org_admin_password": "rata.tata",
        "org_admin_email": "ratan.tata@tcs.com",
        "org_admin_first_name": "Ratan",
        "org_admin_last_name": "Tata"
    }, format="json")
    assert res_fulfill.status_code == status.HTTP_200_OK, f"Fulfillment failed: {res_fulfill.data}"
    tcs_org_id = res_fulfill.data["result"]["organization_id"]
    print(f"--> PASSED: Organization 'tcs' provisioned with ID #{tcs_org_id}")
    print(f"    Subscribed Products:")
    for sub in res_fulfill.data["result"]["subscriptions"]:
        print(f"      - {sub['product_name']}: {sub['license_count']} user seat limit")
    print(f"    Organisation Admin Created: rata.tata / rata.tata")

    # =========================================================================
    # STEP 4: ORGANISATION_ADMIN (rata.tata) provisions software users
    # =========================================================================
    print("\n[STEP 4] ORGANISATION_ADMIN (rata.tata) logs in and provisions end users...")
    res_login_org = client.post("/api/users/login/", {
        "username": "rata.tata",
        "password": "rata.tata",
        "portal_type": "ORGANIZATION"
    }, format="json")
    assert res_login_org.status_code == status.HTTP_200_OK, f"Ratan Tata login failed: {res_login_org.data}"
    token_org = res_login_org.data["access"]
    client.credentials(HTTP_AUTHORIZATION=f"Bearer {token_org}")

    # Provision user 1: K. Krithivasan (CEO) for HRMSM
    res_prov1 = client.post("/api/franchise/organization-users/provision/", {
        "username": "k_krithivasan",
        "email": "k.krithivasan@tcs.com",
        "first_name": "K.",
        "last_name": "Krithivasan",
        "password": "EmployeePass123!",
        "product_name": hrmsm.name,
        "role": "ORG_MANAGER",
        "designation": "Chief Executive Officer",
        "department": "Executive Leadership"
    }, format="json")
    assert res_prov1.status_code == status.HTTP_201_CREATED, f"User provisioning 1 failed: {res_prov1.data}"
    krithi_id = res_prov1.data["user"]["id"]
    print(f"--> PASSED: Org Admin provisioned employee 'k_krithivasan' for HRMSM.")
    print(f"    HRMSM Quota: {res_prov1.data['subscription_status']['used_licenses']}/15 seats used")

    # Link same user to SFA (multi-product license consumption)
    res_prov2 = client.post("/api/franchise/organization-users/provision/", {
        "username": "k_krithivasan",
        "email": "k.krithivasan@tcs.com",
        "first_name": "K.",
        "last_name": "Krithivasan",
        "password": "EmployeePass123!",
        "product_name": sfa.name,
        "role": "ORG_MANAGER",
        "designation": "Chief Executive Officer",
        "department": "Executive Leadership"
    }, format="json")
    assert res_prov2.status_code == status.HTTP_201_CREATED, f"User provisioning 2 failed: {res_prov2.data}"
    assert res_prov2.data["user"]["id"] == krithi_id, "Central user identity preserved"
    print(f"--> PASSED: Org Admin linked same employee 'k_krithivasan' to SFA.")
    print(f"    SFA Quota: {res_prov2.data['subscription_status']['used_licenses']}/10 seats used")

    # =========================================================================
    # STEP 5: End-user K. Krithivasan logs in and verifies launchpad access
    # =========================================================================
    print("\n[STEP 5] SaaS End-User (k_krithivasan) logs in centrally and launches applications...")
    res_login_emp = client.post("/api/users/login/", {
        "username": "k_krithivasan",
        "password": "EmployeePass123!",
        "portal_type": "SAAS"
    }, format="json")
    assert res_login_emp.status_code == status.HTTP_200_OK, f"Employee login failed: {res_login_emp.data}"
    token_emp = res_login_emp.data["access"]
    client.credentials(HTTP_AUTHORIZATION=f"Bearer {token_emp}")

    res_my_portal = client.get("/api/franchise/organization-users/my-portal/")
    assert res_my_portal.status_code == status.HTTP_200_OK, f"my_portal failed: {res_my_portal.data}"
    active_apps = [p["name"] for p in res_my_portal.data["products"]]
    print(f"--> PASSED: SaaS End-User 'k_krithivasan' has active SSO access to: {active_apps}")

    print("\n" + "=" * 80)
    print("DEMO RUN COMPLETED WITH 100% SUCCESS!")
    print("=" * 80)

if __name__ == "__main__":
    run_franchise_team_demo()
